// Merge state agents' region hubs into the site.
// Usage: node scripts/listings/apply_regions.mjs <roundDir> [--dry]
//   <roundDir>/<group>/regions.json -> LOCS region entries in site-seo.js (between the AUTO:regions markers)
//                                      + sections/faq in data/guides.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const [DIR] = process.argv.slice(2);
const DRY = process.argv.includes('--dry');
const seoPath = path.join(REPO, 'site-seo.js');
const guidesPath = path.join(REPO, 'data/guides.json');
const SEO = await import(seoPath);
const STATE_PAGE = Object.fromEntries(Object.entries(SEO.LOCS).filter(([, L]) => L.st).map(([k, L]) => [L.st, k]));

const START = '  // AUTO:regions:start (generated by scripts/listings/apply_regions.mjs — edit regions.json and re-run)';
const END = '  // AUTO:regions:end';
let src = fs.readFileSync(seoPath, 'utf8');
// keep regions merged in earlier rounds unless this round replaces them
const existing = {};
if (src.includes(START)) {
  const block = src.slice(src.indexOf(START), src.indexOf(END));
  for (const m of block.matchAll(/^  ('[^']+'|"[^"]+"): (\{.*\}),$/gm)) existing[JSON.parse(m[1].replace(/'/g, '"'))] = m[2];
}
const guides = JSON.parse(fs.readFileSync(guidesPath, 'utf8'));
const entries = { ...existing };
const log = [];
for (const g of fs.readdirSync(DIR)) {
  const p = path.join(DIR, g, 'regions.json');
  if (!fs.existsSync(p)) continue;
  for (const r of JSON.parse(fs.readFileSync(p, 'utf8'))) {
    const dests = r.hotspots.map((k) => SEO.LOCS[k]).filter(Boolean);
    if (dests.length !== r.hotspots.length) throw new Error(`${r.key}: unknown hotspot in ${r.hotspots}`);
    const st = dests[0].state;
    if (!dests.every((d) => d.state === st)) throw new Error(`${r.key}: hotspots span states`);
    if (SEO.LOCS[r.key] && !SEO.isRegion(SEO.LOCS[r.key])) throw new Error(`${r.key}: clashes with an existing page`);
    const L = { kind: 'region', parent: STATE_PAGE[st], state: st, n: r.n, short: r.short, in: r.in, hotspots: r.hotspots, c: r.c, intro: r.intro, season: r.season };
    entries[r.key] = JSON.stringify(L);
    guides[r.key] = { sections: r.sections, faq: r.faq, ...(r.summary ? { summary: r.summary } : {}), sources: [...new Set((r.sources || []).filter((u) => /^https?:\/\//.test(u)))].slice(0, 8), reviewed: new Date().toISOString().slice(0, 10) };
    log.push(`${r.key} (${st}): ${r.hotspots.join(', ')}`);
  }
}
const block = [START, ...Object.entries(entries).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`), END].join('\n');
if (src.includes(START)) src = src.slice(0, src.indexOf(START)) + block + src.slice(src.indexOf(END) + END.length);
else {
  const anchor = "  // ── Species / style collections (kind: 'species') ──────────────────────────";
  if (!src.includes(anchor)) throw new Error('species anchor not found');
  src = src.replace(anchor, block + '\n' + anchor);
}
console.log(log.join('\n') || 'no regions');
if (!DRY) {
  fs.writeFileSync(seoPath, src);
  fs.writeFileSync(guidesPath, JSON.stringify(guides));
  console.log(`written: ${Object.keys(entries).length} region(s)`);
}
